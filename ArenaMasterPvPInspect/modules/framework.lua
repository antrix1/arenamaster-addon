function AMPVP_CreateTableFromString(inputStr, sep)

	local separator = sep

	if separator == nil then
		separator = "%s"
	end

	local tempTab = {}

	for str in string.gmatch(inputStr, "([^"..separator.."]+)") do

		table.insert(tempTab, str)

	end

	return tempTab

end

