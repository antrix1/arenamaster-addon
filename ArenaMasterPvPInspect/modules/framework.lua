-- AMPVP_AchievementsAndTitlesList is generated by the backend into
-- regionalData/titles.lua (loaded before this file), so a new season's titles need
-- no addon edit. The old hard-coded table stopped at Shadowlands season 4, which
-- is why every Dragonflight / War Within / Midnight title rendered blank.
-- AMPVP_SPECLIST (specialization id => "Spec Class") comes from regionalData/specs.lua.
-- Both are declared here only as a safety net if those files fail to load.
AMPVP_AchievementsAndTitlesList = AMPVP_AchievementsAndTitlesList or {}
AMPVP_SPECLIST = AMPVP_SPECLIST or {}

function AMPVP_ConvertStringToTable(str, character)
  local result = {}
  local index = 1
  
  for s in string.gmatch(str, "[^"..character.."]+") do
    result[index] = s
    index = index + 1
  end

  return result
end

function AMPVP_ConvertRankAchievement(rankName)
	if rankName == nil then
		return ""
	end
	local newTitleName = "";
	
	for rankIndex, name in pairs(AMPVP_AchievementsAndTitlesList) do
	
		if name == rankName then
			for bracketName, bracketColor in pairs(bracketsColors) do
				if string.find(string.lower(rankName), bracketName) then
					newTitleName = bracketsColors[bracketName] .. rankName .. "|r"
				end
			end
		end
	
	end
	
	if newTitleName == "" then
	
		local tempTable = AMPVP_ConvertStringToTable(rankName, " ")
		local rankPoints = nil
		
		for k, v in pairs(tempTable) do
			if tonumber(tempTable[k]) ~= nil then
				rankPoints = tonumber(v)
			end
		end
		
		if rankPoints ~= nil then

			if rankPoints >= 2700 then
				newTitleName = ranksColors[2700]..rankName.."|r"
			elseif rankPoints >= 2400 then
				newTitleName = ranksColors[2400]..rankName.."|r"
			elseif rankPoints >= 2100 then
				newTitleName = ranksColors[2100]..rankName.."|r"
			elseif rankPoints >= 1750 then
				newTitleName = ranksColors[1750]..rankName.."|r"
			elseif rankPoints < 1750 then
				newTitleName = ranksColors[1749]..rankName.."|r"
			end

		end
		
		if newTitleName == "" then
			newTitleName = bracketsColors["none"] .. rankName .. "|r"
		end
	end
	
	return newTitleName
	
end

function AMPVP_ConvertDateToStandardEU(datet)

	if datet == nil then return "No date available" end
	
	local tableMonths = {
		[1] = "January",
		[2] = "February",
		[3] = "March",
		[4] = "April",
		[5] = "May",
		[6] = "June",
		[7] = "July",
		[8] = "August",
		[9] = "September",
		[10] = "October",
		[11] = "November",
		[12] = "December",
	}
	
	local day, month, year = string.split("/", datet)
	
	if day and month and year then
		month = tableMonths[tonumber(month)]
		year = "20"..year
	end
	
	local tempDate = day .." ".. month .." ".. year
	return tempDate
	
end



